import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const sourcePath = path.join(root, 'devDoc/design/character-studio/tokens.json');
export const outputPath = path.join(root, 'desktop/desk-preview/renderer/src/ui/character-tokens.css');
const cssName = name => `--nd-${name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replaceAll('.', '-').toLowerCase()}`;

export function compileTokens(document, selector = '[data-ui-theme="xiacheng"], [data-ui-palette="xiacheng"]') {
  if (document.meta?.format !== 'nowadays.design-tokens/1') throw new Error('Unsupported token format');
  const tokens = new Map();
  const names = new Set();
  const collect = (node, prefix) => {
    if (!node || typeof node !== 'object' || Array.isArray(node)) throw new Error(`Invalid group: ${prefix}`);
    for (const [name, value] of Object.entries(node)) {
      if (!/^(?:[a-z][A-Za-z0-9]*|[0-9]+)$/.test(name)) throw new Error(`Invalid token name: ${name}`);
      const key = `${prefix}.${name}`;
      if (typeof value === 'string') {
        if (/[;{}<>\r\n]/.test(value)) throw new Error(`Unsafe token value: ${key}`);
        const name = cssName(key);
        if (names.has(name)) throw new Error(`Duplicate CSS variable: ${name}`);
        names.add(name); tokens.set(key, value);
      } else collect(value, key);
    }
  };
  for (const layer of ['primitive', 'semantic', 'component']) collect(document[layer], layer);
  const resolve = (key, seen = new Set()) => {
    if (!tokens.has(key)) throw new Error(`Missing reference: ${key}`);
    if (seen.has(key)) throw new Error(`Cyclic reference: ${key}`);
    const value = tokens.get(key);
    if (!value.startsWith('@')) return value;
    return resolve(value.slice(1), new Set([...seen, key]));
  };
  for (const [key, value] of tokens) resolve(key);
  for (const [key, value] of tokens) {
    const layer = key.split('.')[0];
    if (layer === 'primitive' && value.startsWith('@')) throw new Error(`Primitive must be a value: ${key}`);
    if (layer === 'semantic' && !value.startsWith('@primitive.')) throw new Error(`Semantic must reference primitive: ${key}`);
    if (layer === 'component' && !value.startsWith('@semantic.')) throw new Error(`Component must reference semantic: ${key}`);
  }
  const rules = [...tokens].map(([key, value]) => `  ${cssName(key)}: ${value.startsWith('@') ? `var(${cssName(value.slice(1))})` : value};`).join('\n');
  let css = `/* Generated by desktop/scripts/generate-character-theme.mjs; edit tokens.json, not this file. */\n${selector} {\n${rules}\n}\n`;
  for (const [preset, overrides] of Object.entries(document.presets ?? {})) {
    if (!/^[a-z][a-z0-9-]*$/.test(preset)) throw new Error(`Invalid preset: ${preset}`);
    const merged = structuredClone(document); delete merged.presets;
    const merge = (target, patch, prefix = '') => {
      if (!patch || typeof patch !== 'object' || Array.isArray(patch)) throw new Error(`Invalid preset group: ${prefix}`);
      for (const [key, value] of Object.entries(patch)) {
        if (!Object.hasOwn(target, key) || key === 'meta') throw new Error(`Unknown preset token: ${prefix}${key}`);
        if (typeof value === 'string' && typeof target[key] === 'string') target[key] = value;
        else if (typeof target[key] === 'object') merge(target[key], value, `${prefix}${key}.`);
        else throw new Error(`Invalid preset token: ${prefix}${key}`);
      }
    };
    merge(merged, overrides);
    css += compileTokens(merged, `[data-ui-preset="${preset}"]:is([data-ui-theme="xiacheng"], [data-ui-palette="xiacheng"], .ui-modal-backdrop)`);
  }
  return css;
}

async function main() {
  const document = JSON.parse(await fs.readFile(sourcePath, 'utf8'));
  const css = compileTokens(document);
  if (process.argv.includes('--check')) {
    const current = await fs.readFile(outputPath, 'utf8').catch(() => '');
    if (current.replaceAll('\r\n', '\n') !== css) throw new Error('Theme tokens are stale; run npm run tokens (in desktop/desk-preview/renderer)');
    process.stdout.write('Character tokens: up to date\n');
  } else {
    await fs.writeFile(outputPath, css, 'utf8');
    process.stdout.write('Generated scoped character tokens\n');
  }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { process.stderr.write(`${error.message}\n`); process.exitCode = 1; });
}
